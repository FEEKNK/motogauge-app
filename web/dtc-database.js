  /**
   * Lookup DTC metadata by code, with intelligent fallback
   */
  function lookupDTC(code) {
    const formatted = (code || '').toUpperCase().trim();
    if (DTC_CATALOG[formatted]) {
      return {
        code: formatted,
        ...DTC_CATALOG[formatted]
      };
    }

    // Generic fallback for any other OBD2 code
    let system = 'ระบบเครื่องยนต์และระบบไฟฟ้า (General ECU)';
    if (formatted.startsWith('P01')) system = 'ระบบเซนเซอร์จ่ายน้ำมันและอากาศ (Fuel & Air Metering)';
    else if (formatted.startsWith('P02')) system = 'ระบบหัวฉีดน้ำมัน (Fuel Injector Circuit)';
    else if (formatted.startsWith('P03')) system = 'ระบบจุดระเบิดและมัดไฟ (Ignition System)';
    else if (formatted.startsWith('P05')) system = 'ระบบรอบเดินเบาและความเร็ว (Idle & Speed Control)';

    return {
      code: formatted,
      system: system,
      title: `รหัสตรวจพบความผิดปกติ ${formatted}`,
      desc: `กล่อง ECU บันทึกรหัสความบกพร่อง ${formatted} ในหน่วยความจำ แนะนำให้ใช้คู่มือประจำรุ่นตรวจเช็ก`,
      advice: 'บันทึกรหัสนี้ไว้ก่อนกดลบโค้ด เพื่อความปลอดภัยของระบบ',
      severity: 'warning'
    };
  }

